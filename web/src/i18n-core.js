const TEXT={zh:ZH,en:EN};

export function translate(language,key,vars){
  const table=TEXT[language]||ZH;
  let value=table[key]??ZH[key]??key;
  if(vars)for(const [name,replacement] of Object.entries(vars))value=value.replaceAll('{'+name+'}',String(replacement));
  return value;
}

export function detectLanguage(){
  if(typeof window==='undefined')return 'zh';
  const requested=new URLSearchParams(window.location.search).get('lang');
  if(requested&&TEXT[requested])return requested;
  try{const saved=window.localStorage.getItem(STORAGE_KEY);if(saved&&TEXT[saved])return saved;}catch{/* storage can be blocked */}
  return 'zh';
}

// The dashboard remounts on language change, so a module-scope translator stays
// fresh while keeping the dense evidence views readable. This file is deliberately
// React-free: pure view-model and client modules translate without a renderer, and
// `node --test` keeps working with no DOM.
let activeLanguage='zh';

export function setActiveLanguage(language){
  if(TEXT[language])activeLanguage=language;
  return activeLanguage;
}

export function currentLanguage(){
  return activeLanguage;
}

export function tr(key,vars){
  return translate(activeLanguage,key,vars);
}
